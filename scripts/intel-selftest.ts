import assert from 'node:assert/strict';
import { deduplicateIntel, INTEL_DEFAULT, planetIntel, readIntel, safeSourceUrl, writeIntel } from '../lib/intel';
import { parseGdelt } from '../lib/intel-news';

const now = Date.UTC(2026, 10, 25, 12);
const item = { title: 'Published report', url: 'https://example.org/story?utm_source=test', seendate: '20261125T110000Z', sourcecountry: 'United States' };
const records = parseGdelt({ articles: [item, { ...item, url: 'https://example.org/story' }, { ...item, url: 'javascript:alert(1)' }, { ...item, seendate: 'bad' }, { ...item, seendate: '20300101T000000Z' }, {}] }, 'conflicts', now);
assert.equal(records.length, 1);
assert.equal(records[0].lat, null, 'publisher country must never become the event location');
assert.equal(records[0].publishedAt, null, 'indexing date is not publication date');
assert.equal(records[0].observedAt, Date.UTC(2026, 10, 25, 11));
assert.equal(records[0].status, 'Reported');
assert.equal(records[0].sourceUrl, 'https://example.org/story');
assert.equal(deduplicateIntel([...records, ...records]).length, 1);
assert.throws(() => parseGdelt({ error: 'rate limited' }, 'news', now));
assert.equal(safeSourceUrl('https://user:secret@example.org'), null);
assert.equal(safeSourceUrl('data:text/html,test'), null);
assert.deepEqual(readIntel(''), INTEL_DEFAULT);
const params = new URLSearchParams();
const settings = { ...INTEL_DEFAULT, categories: ['accidents', 'space'] as const, hours: 168, selected: 'news:test', query: 'Japan', scope: 'viewport' as const };
writeIntel(params, { ...settings, categories: [...settings.categories] });
assert.deepEqual(readIntel(params.toString()), settings);
assert.deepEqual(readIntel('?intel=unknown&intelHours=Infinity').categories, []);
assert.equal(readIntel('?intelHours=Infinity').hours, 24);
const planet = planetIntel({ quakes: [{ id: 'us1', lat: 0, lon: 0, depth: 12, mag: 5, place: 'Test region', at: now, url: 'https://earthquake.usgs.gov/earthquakes/eventpage/us1', tsunami: false }], events: [], launches: [], fires: null, kp: null, emergencies: null }, now);
assert.equal(planet[0].earthId, 'q:us1');
assert.equal(planet[0].lat, 0);
assert.equal(planet[0].status, 'Official report');
console.log('intel selftest passed: provenance, malformed feeds, unsafe URLs, deduplication, shared links and shared Earth records');
