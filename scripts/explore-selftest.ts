import assert from 'node:assert/strict';
import { appendFix, DEFAULT_FILTER, DEFAULT_LAYERS, matchesAlert, measurement, parseCoordinates, readPreferences, readScene, sceneQuery, trailGeometry, WEATHER_OFF, type Scene } from '../lib/explore';
import { csvRows, firstPoint, importData, validateGeoJSON } from '../lib/import-data';
import { SKY_DEFAULT } from '../lib/sky';
import type { PulseItem } from '../lib/events';

assert.deepEqual(parseCoordinates('40.7, -74.0'), { lat: 40.7, lon: -74 });
assert.deepEqual(parseCoordinates('0 0'), { lat: 0, lon: 0 });
for (const s of ['91, 1', '1, 181', 'Paris', '1,', ',2', 'Infinity,0', '1,2,3']) assert.equal(parseCoordinates(s), null);
assert.deepEqual(readScene('').layers, DEFAULT_LAYERS);
assert.equal(readScene('?c=1,2,99').camera, null);
assert.equal(readScene('?target=flight&id=../../foo').target, null);
const scene: Scene = { camera: { lat: 40, lon: -70, zoom: 9, pitch: 45, bearing: 25 }, layers: { ...DEFAULT_LAYERS, flights: false }, sky: { ...SKY_DEFAULT, sense: 'snow' },
  weather: { ...WEATHER_OFF, radar: true }, stream: null, target: { kind: 'earth', lat: 40, lon: -70, eventId: 'q:test' }, snapshots: false, follow: false };
assert.deepEqual(readScene(sceneQuery(scene)), scene);
assert.deepEqual(readScene('?layers=&sky=').layers, Object.fromEntries(Object.keys(DEFAULT_LAYERS).map((k) => [k, false])));
assert.equal(readScene('?sky=INVALID').sky.sense, null);
assert.deepEqual(readPreferences('{broken'), { places: [], filter: DEFAULT_FILTER });
assert.equal(readPreferences(JSON.stringify({ places: [{ id: 'a', name: 'x', lat: 900, lon: 0, radius: 10 }] })).places.length, 0);
const place = { id: 'p', name: 'Dateline', lat: 0, lon: 179.9, radius: 100 };
const event: PulseItem = { id: 'q:test', kind: 'quake', level: 2, lat: 0, lon: -179.9, title: 'Test', detail: '', at: 0 };
assert(matchesAlert(event, { ...DEFAULT_FILTER, placeId: 'p' }, [place]));
assert(!matchesAlert({ ...event, level: 0 }, DEFAULT_FILTER, [place]));
assert(!matchesAlert(event, { ...DEFAULT_FILTER, kinds: [] }, [place]));
assert(!matchesAlert(event, { ...DEFAULT_FILTER, placeId: 'missing' }, [place]));
const now = 2000000;
let fixes = appendFix([], { lat: 0, lon: 179, at: now - 5000 }, now);
fixes = appendFix(fixes, { lat: 0, lon: -179, at: now }, now);
assert.equal(fixes.length, 2);
assert.equal(appendFix(fixes, fixes[0], now).length, 2);
assert.equal(trailGeometry(fixes).coordinates.length, 0); // Never draw across the whole globe.
assert.equal(appendFix(fixes, { lat: 0, lon: 1, at: now + 20000 }, now).length, 2);
assert.equal(appendFix(fixes, fixes[0], now + 3600000).length, 0);
assert(Math.abs(measurement([[0, 0], [1, 0]]).km - 111.195) < .01);
const area = measurement([[0, 0], [1, 0], [1, 1], [0, 1]]).km2;
assert(area > 12360 && area < 12365);
assert(Math.abs(measurement([[179.5, 0], [-179.5, 0], [-179.5, 1], [179.5, 1]]).km2 - area) < .01);
assert.deepEqual(csvRows('name,lat,lon\r\n"Park, east",40,-74\r\n"Line\nname",41,-73'), [['name', 'lat', 'lon'], ['Park, east', '40', '-74'], ['Line\nname', '41', '-73']]);
const csv = importData('name,latitude,longitude\nA,40,-74\nB,41,-73', 'places.csv');
assert.equal(csv.features.length, 2);
assert.deepEqual(firstPoint(csv), [-74, 40]);
assert.throws(() => importData('latitude,longitude\n,20', 'bad.csv'), /Missing coordinates/);
assert.throws(() => csvRows('"unfinished'), /unclosed/);
assert.throws(() => validateGeoJSON({ type: 'Point', coordinates: [181, 40] }), /Coordinates/);
assert.throws(() => validateGeoJSON({ type: 'Polygon', coordinates: [[[0, 0], [1, 0], [1, 1], [0, 1]]] }), /closed/);
assert.throws(() => validateGeoJSON({ type: 'LineString', coordinates: [[1, 1]] }), /two points/);
const sanitized = validateGeoJSON({ type: 'Feature', geometry: { type: 'Point', coordinates: [0, 0] }, properties: { name: 'A', html: '<script>bad</script>', url: 'javascript:bad' } });
assert.deepEqual(sanitized.features[0].properties, { name: 'A' });
assert.throws(() => validateGeoJSON({ type: 'MultiPoint', coordinates: Array.from({ length: 50001 }, () => [0, 0]) }), /50,000/);
console.log('explore selftest passed: sharing, coordinates, storage, alert filters, trails, geodesy and import boundaries');
